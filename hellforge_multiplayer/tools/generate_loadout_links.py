"""Emit group-local rel32 links from the checked-in image relocation tables.

No game access, image execution, receipt or fingerprint. Existing explicit
bindings stay intact. Only direct calls to another owned entry are selected;
an unexpected reference type or duplicate entry requires a source review.
"""
import argparse
import ast
import re
from pathlib import Path

PROJECT=Path(__file__).resolve().parents[1]
MODULES=('lifecycle','consumers','setup','interactions','refresh','records','frame',
         'mode','control','state','prompt','countdown','resources','resource_owner',
         'resource_tick','resource_events','resource_ownership','resource_sync',
         'resource_signals','resource_actions','resource_main','resource_update')
HEADER=PROJECT/'mod/src/ep_loadout_links_template.h'


def build(peers=False):
    entries={};images=[]
    for index,name in enumerate(MODULES):
        values={}
        for node in ast.parse((PROJECT/f'tools/generate_loadout_{name}.py').read_text()).body:
            if not isinstance(node,ast.Assign):continue
            try:value=ast.literal_eval(node.value)
            except (ValueError,TypeError):continue
            for target in node.targets:
                if isinstance(target,ast.Name):values[target.id]=value
                elif isinstance(target,ast.Tuple):values.update(zip((x.id for x in target.elts),value))
        starts=values.get('STARTS') or [b for b,e in values.get('GROUPS',[])] or [values['START']]
        template='peer_'+name if peers and name in ('consumers','setup','records','mode','countdown') else name
        text=(PROJECT/f'mod/src/ep_loadout_{template}_template.h').read_text()
        match=re.search(r'_entries\[\] = \{([^}]*)\}',text)
        offsets=[int(x,0) for x in match[1].split(',')] if match else [0]
        if len(starts)!=len(offsets):raise ValueError('Entry metadata mismatch: '+name)
        for rva,offset in zip(starts,offsets):
            if rva in entries and not (rva==0x66b090 and name=='resource_update' and entries[rva][0]==14):
                raise ValueError(f'Unreviewed duplicate entry {rva:x}')
            entries[rva]=(index,offset)
        raw=re.search(r'_template\[\] = \{(.*?)\};',text,re.S)[1]
        blob=bytes(int(x,16) for x in re.findall(r'0x([0-9a-f]{2})',raw))
        fixes=[tuple(map(int,x.split(','))) for x in re.findall(r'\{([0-9,-]+)\},',text)]
        images.append((blob,fixes))
    links=[]
    for index,(blob,fixes) in enumerate(images):
        for offset,nxt,key,kind,rva in fixes:
            if key or kind or rva not in entries:continue
            if not offset or nxt!=offset+4 or blob[offset-1]!=0xe8:
                raise ValueError(f'Unreviewed owned entry reference in {MODULES[index]}')
            target,entry=entries[rva]
            links.append((index,target,offset,nxt,rva,entry))
    return links


def render(links,peers=False):
    return ('// Generated by generate_loadout_links.py from saved image relocations.\n'
            'static const EpLoadoutLocalLink '+('ep_loadout_peer_local_links' if peers else 'ep_loadout_local_links')+'[] = {\n'+
            ''.join('    {'+','.join(map(str,row))+'},\n' for row in links)+'};\n')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');args=p.parse_args()
    links=build()
    if args.write:HEADER.write_bytes((render(links)+render(build(True),True)).encode())
    print(f'Generated {len(links)} group-local call bindings; game_access=false')
