"""Derive immutable relocation recipes from the two pinned offline emitters.

No runtime discovery. --write updates the repository header explicitly;
otherwise verify that rebuilding it gives exactly the checked-in bytes.
"""
import argparse
import json
import struct
from pathlib import Path
import native_producer_unwind as producer
import native_receiver_unwind as receiver
from capstone.x86_const import X86_OP_IMM, X86_OP_MEM, X86_REG_RIP

PROJECT=producer.PROJECT
REFERENCE=dict(game_base=0x180000000,code_address=0x190000000,
               roster_address=0x200000000,property_address=0x210000000,reject_address=0x190010000)
HEADER=PROJECT/'mod/src/ep_property_templates.h'


def relocations(code, name):
    md=producer.capstone.Cs(producer.capstone.CS_ARCH_X86,producer.capstone.CS_MODE_64); md.detail=True
    base=REFERENCE['code_address']; instructions=list(md.disasm(code,base))
    producer.require(sum(i.size for i in instructions)==len(code),'Incomplete template decode')
    allowed={0x3483C20}
    if name=='producer': allowed|={0x3326468,0x173B8D0,0x134F190}
    patches=[]
    def relative(ins,offset,width,target):
        if base<=target<base+len(code):
            producer.require(target in {i.address for i in instructions},'Internal target is not an instruction')
            return
        if target==REFERENCE['reject_address']: parameter,addend=4,0
        else:
            addend=target-REFERENCE['game_base']; parameter=0
            producer.require(addend in allowed,'Unknown external reference')
        producer.require(width==4,'Unsupported relative operand')
        patches.append((ins.address-base+offset,ins.address-base+ins.size,parameter,width,addend))
    for ins in instructions:
        if (ins.group(producer.capstone.CS_GRP_JUMP) or ins.group(producer.capstone.CS_GRP_CALL)) and ins.operands[0].type==X86_OP_IMM:
            relative(ins,ins.imm_offset,ins.imm_size,ins.operands[0].imm)
        for operand in ins.operands:
            if operand.type==X86_OP_MEM and operand.mem.base==X86_REG_RIP:
                relative(ins,ins.disp_offset,ins.disp_size,ins.address+ins.size+operand.mem.disp)
        if ins.imm_size==8:
            value=struct.unpack_from('<Q',ins.bytes,ins.imm_offset)[0]
            if value==REFERENCE['roster_address']: parameter,addend=2,0
            elif value==REFERENCE['property_address']-0x3A8: parameter,addend=3,-0x3A8
            else: raise ValueError('Unknown absolute immediate')
            patches.append((ins.address-base+ins.imm_offset,0,parameter,8,addend))
    producer.require(len(patches)==(8 if name=='producer' else 5),'Changed relocation coverage')
    return sorted(patches)


def render():
    source_paths=('tools/native_producer_unwind.py','tools/native_receiver_unwind.py',
                  'tools/native_unwind_source.py','native-unwind-source.lock.json')
    lines=['/* Generated by tools/generate_property_templates.py. Do not edit.',
           ' * Fixed build 25480438; numeric bindings only, no runtime origin proof.']
    for path in source_paths: lines.append(' * '+path+' SHA256 '+producer.sha((PROJECT/path).read_bytes()))
    lines+=[' */']
    facts={}
    for name,module in (('producer',producer),('receiver',receiver)):
        legacy=module.original(**REFERENCE); artifact=module.with_unwind(legacy)
        code=bytes.fromhex(artifact['candidate']['code_hex']); image=bytearray(artifact['image'])
        patches=relocations(code,name)
        for offset,_,_,width,_ in patches: image[offset:offset+width]=bytes(width)
        # Preserve the reference generator's intermediate rel32 preconditions.
        old=[p for p in relocations(bytes.fromhex(legacy['code_hex']),name) if p[3]==4]
        lines.append('static const uint8_t ep_'+name+'_template[] = {')
        for i in range(0,len(image),16): lines.append('    '+','.join(f'0x{x:02x}' for x in image[i:i+16])+',')
        lines.append('};')
        for suffix,rows in (('fixups',patches),('legacy_ranges',old)):
            lines.append(f'static const EpPropertyFixup ep_{name}_{suffix}[] = {{')
            lines += ['    {'+','.join(str(v) for v in row)+'},' for row in rows]
            lines.append('};')
        facts[name]={'image_bytes':len(image),'code_bytes':len(code),'table_offset':artifact['table_offset'],
                     'unwind_offset':artifact['unwind_offset'],'fixups':patches,'legacy_relative_ranges':old}
    return ('\n'.join(lines)+'\n').encode(),facts


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--write',action='store_true')
    args=parser.parse_args(); content,facts=render()
    if args.write: HEADER.write_bytes(content)
    else: producer.require(HEADER.read_bytes()==content,'Property templates differ from pinned emitters; review and regenerate')
    print(json.dumps({'passed':True,'functions':facts,'header_sha256':producer.sha(content),'game_access':False}))
